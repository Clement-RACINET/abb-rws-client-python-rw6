def _failing_connect(url: str, **kwargs: object) -> _FakeWebSocketConnection:
    """Raise before a fake WebSocket can be opened.

    Route: Fake ``websockets.asyncio.client.connect``.

    ABB constraints: This simulates a setup failure after ``POST /subscription``
        but before the WebSocket stream is opened. In that case,
        ``watch_resources`` must perform HTTP fallback cleanup.

    Args:
        url: WebSocket URL.
        **kwargs: WebSocket connection arguments.

    Returns:
        Never returns.

    Raises:
        OSError: Always raised to simulate connection failure.

    Example:
        ```python
        _failing_connect("ws://192.168.125.1:80/poll/1")
        ```
    """
    raise OSError("websocket setup failed")


