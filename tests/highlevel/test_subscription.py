def _build_fake_response(
    headers: dict[str, str],
    text: str,
    status_code: int = 201,
) -> httpx.Response:
    """Build a real httpx.Response for tests.

    Route: N/A — local test helper.

    ABB constraints: The fake response mirrors the response shape consumed by
        ``create_subscription`` after ``POST /subscription``.

    Args:
        headers: Response headers to simulate, e.g. ``Location``.
        text: Response body text.
        status_code: HTTP status code.

    Returns:
        A real ``httpx.Response`` instance.

    Raises:
        No exception is raised by this helper.

    Example:
        ```python
        response = _build_fake_response(
            {"Location": "ws://192.168.125.1:80/poll/1"},
            "<li></li>",
        )
        ```
    """
    return httpx.Response(status_code=status_code, headers=headers, text=text)


def _decode_form_pairs(payload: str) -> list[tuple[str, str]]:
    """Decode a form-urlencoded payload while preserving repeated keys.

    Route: N/A — local test helper.

    ABB constraints: ``POST /subscription`` must repeat the ``resources`` key
        once per resource. A dictionary cannot represent this correctly, so
        tests assert on ordered key-value pairs.

    Args:
        payload: Form-urlencoded payload generated by
            ``_build_subscription_payload``.

    Returns:
        Ordered decoded form key-value pairs.

    Raises:
        No exception is raised by this helper.

    Example:
        ```python
        >>> _decode_form_pairs("resources=1&1=A&1-p=2")
        [('resources', '1'), ('1', 'A'), ('1-p', '2')]
        ```
    """
    return parse_qsl(payload, keep_blank_values=True)


class _FakeRWSClient(RWSClient):
    """Test double for RWSClient.

    Route: N/A — local test double.

    ABB constraints: Only the network-touching methods used by
        ``highlevel.subscription`` are overridden. No real controller is
        contacted.

    Args:
        host: Fake controller host.

    Returns:
        Fake RWS client instance.

    Raises:
        No exception is raised by this test double constructor.

    Example:
        ```python
        client = _FakeRWSClient()
        ```
    """

    def __init__(self, host: str = "192.168.125.1") -> None:
        super().__init__(host=host)
        self.post_calls: list[tuple[str, dict[str, object]]] = []
        self.delete_calls: list[tuple[str, dict[str, object]]] = []
        self._post_response: httpx.Response | None = None
        self._delete_response = httpx.Response(status_code=204)
        self._fake_cookie_header = "-http-session-=abc123; ABBCX=xyz789"

    def set_post_response(self, response: httpx.Response) -> None:
        """Configure the response returned by the next ``post`` call.

        Route: N/A — local test helper.

        ABB constraints: None.

        Args:
            response: Fake response returned by ``post``.

        Returns:
            None.

        Raises:
            No exception is raised by this helper.

        Example:
            ```python
            client.set_post_response(httpx.Response(201))
            ```
        """
        self._post_response = response

    async def post(self, path: str, **kwargs: object) -> httpx.Response:
        """Record a fake POST call and return the configured response.

        Route: Fake ``POST`` transport method.

        ABB constraints: Used to simulate ``POST /subscription``.

        Args:
            path: Requested RWS path.
            **kwargs: Request arguments.

        Returns:
            Configured fake response.

        Raises:
            AssertionError: If no fake response was configured.

        Example:
            ```python
            response = await client.post("/subscription", content="...")
            ```
        """
        self.post_calls.append((path, kwargs))
        assert self._post_response is not None, "post() called without a response"
        return self._post_response

    async def delete(self, path: str, **kwargs: object) -> httpx.Response:
        """Record a fake DELETE call and return the configured response.

        Route: Fake ``DELETE`` transport method.

        ABB constraints: Used to simulate ``DELETE /subscription/{group-id}``.

        Args:
            path: Requested RWS path.
            **kwargs: Request arguments.

        Returns:
            Fake delete response.

        Raises:
            No exception is raised by this fake method.

        Example:
            ```python
            response = await client.delete("/subscription/7")
            ```
        """
        self.delete_calls.append((path, kwargs))
        return self._delete_response

    def session_cookie_header(self) -> str:
        """Return a fixed fake cookie header.

        Route: N/A — local fake session helper.

        ABB constraints: RWS WebSocket subscription handshakes must reuse the
            HTTP session cookies.

        Args:
            None.

        Returns:
            Fake cookie header.

        Raises:
            No exception is raised by this fake method.

        Example:
            ```python
            cookie = client.session_cookie_header()
            ```
        """
        return self._fake_cookie_header


class _FakeWebSocketConnection:
    """Async context manager and iterator standing in for a WebSocket.

    Route: Fake WebSocket ``ws://.../poll/{group-id}``.

    ABB constraints: Mimics the message stream consumed by ``watch_resources``.

    Args:
        messages: Text messages yielded by the fake WebSocket.

    Returns:
        Fake WebSocket connection.

    Raises:
        No exception is raised by this fake constructor.

    Example:
        ```python
        websocket = _FakeWebSocketConnection(["<li></li>"])
        ```
    """

    def __init__(self, messages: list[str]) -> None:
        self._messages = list(messages)

    async def __aenter__(self) -> _FakeWebSocketConnection:
        """Enter the fake WebSocket context.

        Route: Fake WebSocket context manager.

        ABB constraints: None.

        Args:
            None.

        Returns:
            The fake WebSocket connection itself.

        Raises:
            No exception is raised by this fake method.

        Example:
            ```python
            async with _FakeWebSocketConnection([]) as websocket:
                ...
            ```
        """
        return self

    async def __aexit__(self, *exc_info: object) -> bool:
        """Exit the fake WebSocket context.

        Route: Fake WebSocket context manager.

        ABB constraints: Closing the real WebSocket cleans up ABB subscription
            groups server-side. This fake simply exits.

        Args:
            *exc_info: Exception information from the context manager.

        Returns:
            ``False`` so exceptions are not suppressed.

        Raises:
            No exception is raised by this fake method.

        Example:
            ```python
            async with _FakeWebSocketConnection([]):
                ...
            ```
        """
        return False

    def __aiter__(self) -> _FakeWebSocketConnection:
        """Return the async iterator.

        Route: Fake WebSocket message iterator.

        ABB constraints: None.

        Args:
            None.

        Returns:
            The fake WebSocket connection itself.

        Raises:
            No exception is raised by this fake method.

        Example:
            ```python
            async for message in websocket:
                ...
            ```
        """
        return self

    async def __anext__(self) -> str:
        """Yield the next fake WebSocket message.

        Route: Fake WebSocket message iterator.

        ABB constraints: None.

        Args:
            None.

        Returns:
            Next fake WebSocket message.

        Raises:
            StopAsyncIteration: When all messages have been consumed.

        Example:
            ```python
            message = await websocket.__anext__()
            ```
        """
        if not self._messages:
            raise StopAsyncIteration
        return self._messages.pop(0)


