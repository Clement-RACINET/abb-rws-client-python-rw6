    assert handle.initial_values == {"a": "1"}

    path, kwargs = client.post_calls[0]
    assert path == "/subscription"
    assert kwargs["content"] == ("resources=1&1=%2Frw%2Fiosystem%2Fsignals%2FA%3Bstate&1-p=1")


